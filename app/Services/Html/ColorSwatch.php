namespace App\Services\Html;

/**
 * Vendor variant `color` text is free-form (e.g. "Glossy", "Matte", "Rose
 * Gold", "Space Gray") — most of it isn't a real CSS color at all, so
 * dropping it straight into a `background` declaration silently renders an
 * invisible swatch for anything that isn't a literal CSS keyword. Resolve
 * only the labels we can confidently render as a color; callers should
 * fall back to a text-label pill when this returns null.
 */
class ColorSwatch
{
    /** Standard CSS color keywords, already lowercased with no separators. */
    private const CSS_COLOR_KEYWORDS = [
        'aliceblue', 'antiquewhite', 'aqua', 'aquamarine', 'azure', 'beige', 'bisque', 'black',
