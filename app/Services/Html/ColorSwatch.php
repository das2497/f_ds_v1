    /**
     * Resolves a vendor color label to a safe CSS color keyword, or null
     * when it isn't one. Strips spaces/punctuation first so compound
     * keywords vendors commonly write with a space ("Light Blue", "Hot
     * Pink") still resolve, since the real CSS keywords are single words
     * ("lightblue", "hotpink").
     */
    public static function resolve(?string $label): ?string
    {
        if (blank($label)) {
            return null;
        }

        $normalized = strtolower(preg_replace('/[^a-z]/i', '', $label) ?? '');

        return in_array($normalized, self::CSS_COLOR_KEYWORDS, true) ? $normalized : null;
    }
}
